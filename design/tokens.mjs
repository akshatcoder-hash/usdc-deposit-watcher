// Builds public/tokens.css from OKLCH ramps and measures every text pair.
// Run: bun design/tokens.mjs
import { clampChroma, converter, formatHex, wcagContrast } from "culori";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const toOklch = converter("oklch");
const color = (l, c, h) => formatHex(clampChroma({ mode: "oklch", l, c, h }, "oklch"));
const HUE = { neutral: 262, ok: 160, warn: 78, danger: 24 };
// neutral carries a faint cool tint; status hues use a proportion of their own gamut limit
const neutral = (l, tint = 0.012) => color(l, tint, HUE.neutral);
const hued = (name, l, c = 0.17) => color(l, c, HUE[name]);

const THEMES = {
  dark: {
    bg: neutral(0.15), surface: neutral(0.185), border: neutral(0.26), borderStrong: neutral(0.33),
    text: neutral(0.95, 0.006), muted: neutral(0.7, 0.01),
    ok: hued("ok", 0.8), okSolid: hued("ok", 0.8, 0.15), okShade: hued("ok", 0.62, 0.13), okEdge: hued("ok", 0.9, 0.1),
    warn: hued("warn", 0.82), warnSolid: hued("warn", 0.82, 0.15), warnShade: hued("warn", 0.64, 0.13), warnEdge: hued("warn", 0.9, 0.1),
    danger: hued("danger", 0.72), grey: neutral(0.62, 0.012), greyShade: neutral(0.46, 0.012), greyEdge: neutral(0.76, 0.01),
    onSolid: neutral(0.15),
    m: { paper: neutral(0.185), face: neutral(0.22), top: neutral(0.26), s0: neutral(0.17), s1: neutral(0.2), s2: neutral(0.235), s3: neutral(0.27), litTop: neutral(0.31), litShade: neutral(0.25),
      hi: neutral(0.82), mid: neutral(0.58), lo: neutral(0.4), faint: neutral(0.3), lit: neutral(0.97, 0.004), halo: neutral(0.1), haloOpacity: 0.9, dot: neutral(0.93) },
  },
  light: {
    bg: neutral(0.968, 0.006), surface: neutral(0.995, 0.003), border: neutral(0.9, 0.006), borderStrong: neutral(0.84, 0.008),
    text: neutral(0.2, 0.012), muted: neutral(0.48, 0.014),
    ok: hued("ok", 0.46, 0.13), okSolid: hued("ok", 0.7, 0.16), okShade: hued("ok", 0.58, 0.14), okEdge: hued("ok", 0.42, 0.11),
    warn: hued("warn", 0.5, 0.11), warnSolid: hued("warn", 0.8, 0.15), warnShade: hued("warn", 0.66, 0.14), warnEdge: hued("warn", 0.5, 0.1),
    danger: hued("danger", 0.5, 0.18), grey: neutral(0.68, 0.012), greyShade: neutral(0.56, 0.012), greyEdge: neutral(0.42, 0.012),
    onSolid: neutral(0.99, 0.004),
    m: { paper: neutral(0.995, 0.004), face: neutral(0.998, 0.003), top: neutral(0.999, 0.002), s0: neutral(0.89, 0.008), s1: neutral(0.915, 0.008), s2: neutral(0.94, 0.007), s3: neutral(0.962, 0.006), litTop: neutral(0.999, 0.002), litShade: neutral(0.95, 0.006),
      hi: neutral(0.3, 0.012), mid: neutral(0.58, 0.012), lo: neutral(0.78, 0.01), faint: neutral(0.88, 0.008), lit: neutral(0.1, 0.01), halo: neutral(0.6, 0.02), haloOpacity: 0.3, dot: neutral(0.28, 0.01) },
  },
};

// text pairs that must pass 4.5:1 (body and small text), checked on the surface they render on
const PAIRS = [
  ["text", "bg"], ["text", "surface"], ["muted", "bg"], ["muted", "surface"],
  ["ok", "bg"], ["ok", "surface"], ["warn", "bg"], ["warn", "surface"], ["danger", "bg"], ["danger", "surface"],
];
let failed = 0;
const rows = [];
for (const [name, t] of Object.entries(THEMES)) {
  for (const [fg, bg] of PAIRS) {
    const ratio = wcagContrast(t[fg], t[bg]);
    rows.push(`${name.padEnd(5)} ${fg.padEnd(7)} on ${bg.padEnd(7)} ${ratio.toFixed(2)}${ratio < 4.5 ? "  FAIL" : ""}`);
    if (ratio < 4.5) failed++;
  }
}
console.log(rows.join("\n"));

const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const block = (name, t) => {
  const sem = ["bg", "surface", "border", "borderStrong", "text", "muted", "ok", "okSolid", "okShade", "okEdge", "warn", "warnSolid", "warnShade", "warnEdge", "danger", "grey", "greyShade", "greyEdge", "onSolid"]
    .map((k) => `  --c-${kebab(k)}: ${t[k]};`).join("\n");
  const m = Object.entries(t.m).map(([k, v]) => `  --m-${kebab(k)}: ${v};`).join("\n");
  return `:root[data-theme="${name}"] {\n  color-scheme: ${name};\n${sem}\n${m}\n}`;
};
const css = `/* generated by design/tokens.mjs from OKLCH ramps. Do not edit by hand. */\n${block("dark", THEMES.dark)}\n\n${block("light", THEMES.light)}\n`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "..", "public", "tokens.css"), css);
console.log(failed ? `${failed} pair(s) below 4.5:1` : "all text pairs pass 4.5:1");
process.exit(failed ? 1 : 0);
